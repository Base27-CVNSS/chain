const assert=require("node:assert/strict");
globalThis.window=globalThis;
require("../data.js");
require("../registry-core.js");
require("../registry-snapshot.js");
require("../chain-taxonomy.js");
const original=globalThis.DATA;
const merged=globalThis.ChainRegistryCore.apply(original,globalThis.CHAIN_REGISTRY_SNAPSHOT);
const classify=globalThis.ChainTaxonomy.classify;
const totals=globalThis.ChainTaxonomy.summary(merged);
const byName=name=>{const d=merged.find(x=>x.n===name);assert(d,"Missing: "+name);return d};
assert.equal(merged.length,600);
assert.equal(new Set(merged.filter(x=>x.chainId).map(x=>x.chainId)).size,merged.filter(x=>x.chainId).length,"Unique network chain ID");
assert.equal(classify(byName("Solana")).smart,"yes");
assert.equal(classify(byName("Solana")).evm,"no");
assert.equal(classify(byName("Algorand")).evm,"no");
assert.equal(byName("Algorand").chainId,undefined);
assert.equal(classify(byName("Algorand")).runtime,"AVM / TEAL");
assert.match(classify(byName("Polkadot")).runtime,/Hub/);
assert.equal(byName("Polkadot").chainId,undefined);
assert.equal(classify(byName("Bitcoin")).smart,"limited");
assert.equal(classify(byName("Base")).evm,"yes");
assert.equal(classify(byName("Base")).fork.status,"unknown","Ethereum L2 != history or code fork");
assert.equal(classify(byName("Bitcoin Cash")).fork.type,"history");
assert.equal(classify(byName("Ethereum Classic")).fork.type,"history");
assert.equal(classify(byName("Dogecoin")).fork.type,"code");
assert.equal(classify(byName("Binance Smart Chain")).fork.type,"code");
assert.equal(classify(byName("Polygon")).fork.type,"code");
assert(totals.smartYes>0&&totals.smartUnknown>0&&totals.forkDocumented>0);
assert.equal(totals.smartYes+totals.smartLimited+totals.smartEcosystem+totals.smartUnknown,600);
assert.equal(totals.evmYes+totals.evmNo+totals.evmUnknown,600);
console.log("PASS 600 chains, canonical IDs, runtime/lineage distinctions:",totals);
