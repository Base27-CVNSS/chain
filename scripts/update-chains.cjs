// Refresh ChainScope's static registry snapshot from a public list (not a node liveness audit).
const fs=require("node:fs");
const path=require("node:path");
globalThis.window=globalThis;
require("../data.js");
require("../chain-logos.js");
const core=require("../registry-core.js");
async function run(){
 const origin="https://chainlist.org/rpcs.json";
 const response=await fetch(origin,{signal:AbortSignal.timeout(60000),headers:{"accept":"application/json"}});
 if(!response.ok)throw new Error("ChainList HTTP "+response.status);
 const entries=await response.json();
 const generated=core.filterRegistry(entries,globalThis.DATA,globalThis.CHAIN_LOGO_FILES,core.TARGET);
 const combined=core.apply(globalThis.DATA,generated);
 if(combined.length<550||combined.length>650)throw new Error("Out-of-range verified registry candidates: "+combined.length);
 if(new Set(combined.filter(x=>x.chainId).map(x=>x.chainId)).size!==combined.filter(x=>x.chainId).length)throw new Error("Duplicate chainIDs");
 const fetchedAt=new Date().toISOString();
 const out={
   ...generated,
   fetchedAt,
   target:core.TARGET,
   source:"https://chainlist.org/rpcs.json",
   iconSource:"https://github.com/DefiLlama/icons/tree/v2/assets/chains",
   note:"Listed networks are not verified to be operational; token counts and prices are not live."
 };
 const js="/* AUTOGENERATED by scripts/update-chains.cjs. Source: chainlist.org/rpcs.json. */\nwindow.CHAIN_REGISTRY_SNAPSHOT="+JSON.stringify(out)+";\n";
 fs.writeFileSync(path.join(__dirname,"..","registry-snapshot.js"),js);
 console.log("Registry size: "+entries.length+" source records; "+out.extras.length+" new EVM entries; "+combined.length+" combined entries; "+out.extras.filter(x=>x.logoLikely).length+" index-matched icon candidates; generated "+fetchedAt);
}
run().catch(e=>{console.error(e);process.exitCode=1});
